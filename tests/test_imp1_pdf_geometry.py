def geometry_pdf():
    pages = [[], []]
    repeated = []
    for row in _GEOMETRY.strip().splitlines():
        page, top, words = row.split("|")
        for word in words.split(";"):
            x, text = word.split(":", 1)
            position = (int(x), int(top), text)
            pages[int(page) - 1].append(position)
            if int(page) == 1 and (int(top) <= 115 or int(top) >= 413):
                repeated.append(position)
    pages[1] += repeated
    return _minimal_text_pdf(pages, exact_words=True)


class TestMeasuredSupplierLayout(unittest.TestCase):
    def test_off_center_invoice_copies_and_staggered_item_rows(self):
        invoice = extract_structured("pdf", geometry_pdf())
        self.assertEqual(len(invoice.lines), 17, invoice.warnings)
        self.assertEqual(invoice.warnings, [])
        self.assertEqual(invoice.supplier_name, "مخزن الهتون")
